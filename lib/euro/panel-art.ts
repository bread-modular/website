// Pen drawings on the faceplates: white and gold lines that show the signal
// flow, as on our hand-labelled panels. Coordinates are panel millimetres (see
// panels.json); gold is the audio path, white is control and framing.

export interface Stroke {
  pts: number[];      // x1, y1, x2, y2, ...
  gold?: boolean;
  arrow?: boolean;    // arrowhead at the last point
  smooth?: boolean;   // curve through the points
}

export interface ArtLabel {
  text: string;
  x: number;
  y: number;
  size: number;
  gold?: boolean;
  turn?: boolean;     // written bottom to top
}

export interface PanelArt {
  strokes: Stroke[];
  labels?: ArtLabel[];
  big?: string[];     // pots that take the big white knob
}

const W = (...pts: number[]): Stroke => ({ pts });
const WA = (...pts: number[]): Stroke => ({ pts, arrow: true });
const G = (...pts: number[]): Stroke => ({ pts, gold: true });
const GA = (...pts: number[]): Stroke => ({ pts, gold: true, arrow: true });
const GS = (...pts: number[]): Stroke => ({ pts, gold: true, smooth: true });
const box = (x: number, y: number, w: number, h: number): number[] => [x, y, x + w, y, x + w, y + h, x, y + h, x, y];

