#!/usr/bin/env node
// Builds the firmware settings pages into the site. Each page is a single file
// web app in the Eurorack hardware repo (index.html, plus the generated demo.js);
// this splits it into modules under app/firmwares/apps/<id>/ that /firmwares/<id>
// loads when the firmware is opened, and runs in a shadow root (AppHost.tsx).
//
//   node scripts/sync-firmware-apps.mjs <path to the Eurorack hardware repo>
//
// Run it again after the page or its demo.js changes in the repo.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// website id -> folder of the page in the repo, the demo answer's name in demo.js
// (keep the ids in sync with lib/euro/firmwares.ts and app/firmwares/apps/index.ts)
const APPS = [
  { id: '32bit-master', dir: 'modules/32bit/firmware/master/web', demo: 'MASTER_DEMO' },
];

const repo = process.argv[2];
if (!repo) {
  console.error('Usage: node scripts/sync-firmware-apps.mjs <path to the Eurorack hardware repo>');
  process.exit(1);
}
const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function between(text, start, end, what) {
  const a = text.indexOf(start);
  const b = a < 0 ? -1 : text.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`${what}: no ${start} .. ${end}`);
  return text.slice(a + start.length, b);
}

// The page's CSS on the shadow root: :root is the host, <body> the .ms-body div.
// The app fills its box (the page set 100vh); fixed layers (phone drawer, an
// effect full screen, the touch sheet) stay inside the box (contain: layout).
function scopeCss(css) {
  const scoped = css
    .replace(/:root\s*\{/g, ':host {')
    .replace(/html,\s*body\s*\{/g, '.ms-body {')
    .replace(/(^|[\s,{}(])body(?=[\s.,:{])/g, '$1.ms-body');
  if (/(^|[\s,{}(])(html|body)[\s.,:{]/.test(scoped)) throw new Error('CSS: html or body left after scoping');
  return [
    ':host { all: initial; display: block; height: 100%; }',
    scoped.trim(),
    '.ms-body { position: relative; contain: layout; }',
    '#app, .ms-body.mobile #app { height: 100%; }',
  ].join('\n');
}

const header = (src) => `// Generated by scripts/sync-firmware-apps.mjs from ${src}. Do not edit:\n// change the page in the hardware repo and sync again.\n`;

for (const app of APPS) {
  const src = join(repo, app.dir);
  const html = readFileSync(join(src, 'index.html'), 'utf8');
  const out = join(site, 'app/firmwares/apps', app.id);
  mkdirSync(out, { recursive: true });
  const from = `${app.dir}/index.html`;

  const css = scopeCss(between(html, '<style>', '</style>', 'style'));
  const markup = between(html, '<body>', '<script', 'body').trim();
  const body = html.slice(html.indexOf('<body>'));
  const script = between(body.slice(body.indexOf('<script>')), '<script>', '</script>', 'script').trim();
  // Unmounting the page closes its link (the serial port or the demo)
  if (!/\bconst state = /.test(script) || !/\bfunction disconnect\(/.test(script)) {
    throw new Error(`${from}: no state or disconnect() to close the link with`);
  }
  const hasDemo = existsSync(join(src, 'demo.js'));

  writeFileSync(join(out, 'style.ts'), `${header(from)}\nconst style = ${JSON.stringify(css)};\n\nexport default style;\n`);
  writeFileSync(join(out, 'markup.ts'), `${header(from)}\nconst markup = ${JSON.stringify(markup)};\n\nexport default markup;\n`);
  writeFileSync(join(out, 'app.js'), [
    header(from) + '/* eslint-disable */',
    hasDemo ? `import { ${app.demo} } from './demo.js';\n` : '',
    '// The page\'s script. AppHost.tsx runs it on the shadow root: document, window,',
    '// the listeners and the timers are scoped to it, and the returned function closes it.',
    'export default function run(document, window, addEventListener, matchMedia, setInterval, setTimeout, requestAnimationFrame) {',
    script,
    'return () => { if (state.link) disconnect(); };',
    '}',
    '',
  ].join('\n'));
  if (hasDemo) {
    const demo = readFileSync(join(src, 'demo.js'), 'utf8');
    if (!demo.includes(`const ${app.demo} =`)) throw new Error(`${app.dir}/demo.js: no const ${app.demo}`);
    writeFileSync(join(out, 'demo.js'), `${header(`${app.dir}/demo.js`)}${demo.replace(`const ${app.demo} =`, `export const ${app.demo} =`)}`);
  }
  console.log(`${app.id} <- ${app.dir}`);
}
